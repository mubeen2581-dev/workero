export const calculateJobProfitability = (job: Job) => {
  const materialCost = job.materials.reduce((sum, material) => sum + material.totalPrice, 0);
  const laborCost = (job.actualDuration || job.estimatedDuration) * 75; // £75/hour labor rate
  const totalCost = materialCost + laborCost;
  
  // Mock quote value - in real app this would come from the quote
  const quoteValue = 15000; // This would be fetched from the quote
  const profit = quoteValue - totalCost;
  const profitMargin = quoteValue > 0 ? (profit / quoteValue) * 100 : 0;
  
  return {
    materialCost,
    laborCost,
    totalCost,
    profit,
    profitMargin,
  };
};
